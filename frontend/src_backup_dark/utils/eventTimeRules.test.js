import test from 'node:test';
import assert from 'node:assert/strict';
import {startTimeError, pricingTimeError} from './eventTimeRules.js';
const now=Date.parse('2026-10-07T13:00:30Z');
test('start earlier minute on same day is rejected',()=>assert.ok(startTimeError('2026-10-07T13:00:00Z',now)));
test('start equal to now is rejected',()=>assert.ok(startTimeError('2026-10-07T13:00:30Z',now)));
test('future minute on same day is accepted',()=>assert.equal(startTimeError('2026-10-07T13:01:00Z',now),''));
test('invalid start is rejected',()=>assert.ok(startTimeError('bad',now)));
test('save rechecks clock after form has stayed open',()=>assert.ok(startTimeError('2026-10-07T13:01:00Z',now+60000)));
const rule={ruleType:'EarlyBird',triggerFrom:'2026-10-07T13:01:00Z',triggerTo:'2026-10-07T14:00:00Z'};
const ticket={salesStartsAt:'2026-10-07T13:00:00Z',salesEndsAt:'2026-10-08T13:00:00Z'};
const event={startsAt:'2026-10-08T14:00:00Z'};
test('valid future discount interval is accepted',()=>assert.equal(pricingTimeError(rule,ticket,event,now),''));
test('discount needs both times',()=>assert.ok(pricingTimeError({...rule,triggerTo:''},ticket,event,now)));
test('discount same-day past minute is rejected',()=>assert.ok(pricingTimeError({...rule,triggerFrom:'2026-10-07T13:00:00Z'},ticket,event,now)));
test('discount end must be after start',()=>assert.ok(pricingTimeError({...rule,triggerTo:rule.triggerFrom},ticket,event,now)));
test('discount cannot start before sales',()=>assert.ok(pricingTimeError(rule,{...ticket,salesStartsAt:'2026-10-07T13:30:00Z'},event,now)));
test('discount cannot end after sales',()=>assert.ok(pricingTimeError(rule,{...ticket,salesEndsAt:'2026-10-07T13:30:00Z'},event,now)));
test('discount cannot end after concert start',()=>assert.ok(pricingTimeError(rule,ticket,{startsAt:'2026-10-07T13:30:00Z'},now)));
test('quantity rule does not require a time interval',()=>assert.equal(pricingTimeError({ruleType:'QuantityBased'},ticket,event,now),''));
