-- Run this script after connecting to queue_db.

BEGIN;

CREATE TABLE IF NOT EXISTS public.queue_configurations (
    queue_configuration_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL,
    pre_queue_start_time timestamp without time zone NOT NULL,
    pre_queue_end_time timestamp without time zone NOT NULL,
    admission_rate integer NOT NULL,
    queue_enabled boolean NOT NULL DEFAULT true,
    fairness_policy character varying(40) NOT NULL DEFAULT 'RANDOMIZED',
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    updated_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_queue_configurations_event_id
    ON public.queue_configurations (event_id);

CREATE TABLE IF NOT EXISTS public.queue_sessions (
    queue_session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL,
    user_id integer NOT NULL,
    session_id text NOT NULL,
    queue_token text NOT NULL,
    status text NOT NULL DEFAULT 'REGISTERED',
    position integer,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    updated_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ix_queue_sessions_event_id_user_id
    ON public.queue_sessions (event_id, user_id);

CREATE UNIQUE INDEX IF NOT EXISTS ix_queue_sessions_queue_token
    ON public.queue_sessions (queue_token);

CREATE TABLE IF NOT EXISTS public.queue_abuse_alerts (
    abuse_alert_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id integer NOT NULL,
    user_id integer NOT NULL,
    session_id text NOT NULL,
    queue_token text NOT NULL,
    alert_type text NOT NULL,
    severity text NOT NULL DEFAULT 'LOW',
    status text NOT NULL DEFAULT 'OPEN',
    detected_behavior text NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_queue_abuse_alerts_event_id_created_at
    ON public.queue_abuse_alerts (event_id, created_at);

CREATE UNIQUE INDEX IF NOT EXISTS ux_queue_abuse_alerts_session_type
    ON public.queue_abuse_alerts (session_id, alert_type)
    WHERE alert_type IN (
        'MULTIPLE_REGISTRATION_ATTEMPTS',
        'AUTOMATED_REQUEST_PATTERN',
        'TOKEN_REPLAY'
    );

COMMIT;
